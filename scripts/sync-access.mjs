import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "config", "allowed-emails.json");
const frontendPath = path.join(root, "public", "allowed-emails.js");
const rulesPath = path.join(root, "firestore.rules");
const rulesStart = "        // BEGIN GENERATED ALLOWED EMAILS";
const rulesEnd = "        // END GENERATED ALLOWED EMAILS";

const source = JSON.parse(await readFile(sourcePath, "utf8"));

if (!Array.isArray(source) || source.length === 0) {
  throw new Error("config/allowed-emails.json must contain at least one email.");
}

const emails = source.map(email => String(email).trim().toLowerCase());
const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

if (emails.some(email => !emailPattern.test(email))) {
  throw new Error("config/allowed-emails.json contains an invalid email.");
}

if (new Set(emails).size !== emails.length) {
  throw new Error("config/allowed-emails.json contains duplicate emails.");
}

const frontend = `// Generated by scripts/sync-access.mjs. Do not edit directly.\nexport const allowedEmails = ${JSON.stringify(emails, null, 2)};\n`;
await writeFile(frontendPath, frontend, "utf8");

const rules = await readFile(rulesPath, "utf8");
const startIndex = rules.indexOf(rulesStart);
const endIndex = rules.indexOf(rulesEnd);

if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
  throw new Error("Generated email markers are missing or invalid in firestore.rules.");
}

const generatedRules = [
  rulesStart,
  ...emails.map((email, index) => `          '${email}'${index < emails.length - 1 ? "," : ""}`),
  rulesEnd
].join("\n");

const updatedRules = `${rules.slice(0, startIndex)}${generatedRules}${rules.slice(endIndex + rulesEnd.length)}`;
await writeFile(rulesPath, updatedRules, "utf8");

console.log(`Synchronized ${emails.length} allowed emails.`);